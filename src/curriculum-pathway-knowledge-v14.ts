function pathwayFoundationConcept(input: PathwayKnowledgeInput): ReviewedConcept {
  const label = input.pathway ? input.pathway.replace(/-/g, ' ') : input.subject
  return c(
    `${input.title}的核心模型與證據`,
    `本單元屬於 ${label} 路線，學習範圍是：${input.focus}。除了各項專有概念，還要能說明使用哪些定義、數量、文本或資料來支持判斷，並指出模型的適用條件與限制。`,
    `完成「${input.title}」的題目時，先指出一個本單元專有概念，再用一項具體條件或資料說明它如何影響結論。`,
  )
}

export function getPathwayKnowledgeProfileV14(input: PathwayKnowledgeInput): PathwayKnowledgeProfile {
  if (!input.pathway || !RULES[input.pathway]) return { concepts: [], matchedRules: [] }
  const haystack = `${input.title} ${input.focus}`
  const rules = RULES[input.pathway] ?? []
  const matched = rules.filter((rule) => rule.match.test(haystack))
  const concepts = matched.map((rule) => rule.concept)
  if (concepts.length < 4) concepts.push(pathwayFoundationConcept(input))
  return {
    concepts: uniqueConcepts(concepts).slice(0, 7),
    matchedRules: matched.map((rule) => rule.id),
  }
}

function uniqueConcepts(concepts: ReviewedConcept[]) {
  const seen = new Set<string>()
  return concepts.filter((concept) => {
    const key = concept.title.replace(/[\s「」『』（）()]/g, '')
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })
}
