function noteForTrack(grade: number, subject: CurriculumSubjectId) {
  if (grade <= 2 && (subject === 'science' || subject === 'social')) {
    return '國小低年級官方課程以「生活課程」跨領域統整為主；平台為了維持國英數自社入口，將相關內容分別映射到自然與社會，但教學活動仍應以生活情境跨域設計。'
  }
  if (grade <= 2 && subject === 'english') {
    return '低年級英語在各校常以校本或彈性課程方式啟蒙；此處標示為平台延伸路線，不視為全國一致的國定年級進度。'
  }
  if (grade >= 11 && subject === 'math') {
    return '高中後段正式教材需再依數學 A／數學 B 等課程路線分流；此版本先保留共同能力骨架。'
  }
  if (grade >= 10 && subject === 'science') {
    return '高中自然科學實際會分成物理、化學、生物、地球科學與選修；此處先以「自然」總入口整理共同藍圖。'
  }
  if (grade >= 10 && subject === 'social') {
    return '高中社會領域實際會分成地理、歷史、公民與社會及相關選修；此處先以「社會」總入口整理共同藍圖。'
  }
  return undefined
}

function unitId(grade: number, subject: CurriculumSubjectId, semester: CurriculumSemester, index: number) {
  return `g${grade}-${subject}-s${semester}-u${index + 1}`
}

function toUnits(grade: number, subject: CurriculumSubjectId, semester: CurriculumSemester, raw: RawUnit[]): CurriculumUnitPlan[] {
  return raw.map(([title, focus], index) => ({
    id: unitId(grade, subject, semester, index),
    title,
    focus,
    difficultyBand: index === 0 ? 'foundation' : index === raw.length - 1 ? 'stretch' : 'core',
    prerequisiteSkills: [],
    lessonIds: [],
  }))
}

export function getCurriculumTrack(grade: number, subject: CurriculumSubjectId): CurriculumTrackPlan | null {
  const raw = subjectRoadmaps[subject]?.[grade]
  if (!raw) return null
  return {
    grade,
    subject,
    note: noteForTrack(grade, subject),
    sourceBasis: ROADMAP_SOURCE,
    semesters: [
      { semester: 1, units: toUnits(grade, subject, 1, raw[0]) },
      { semester: 2, units: toUnits(grade, subject, 2, raw[1]) },
    ],
  }
}

export function gradeNumberFromStage(stage: 'elementary' | 'junior' | 'senior', gradeIndex: number) {
  if (stage === 'elementary') return gradeIndex + 1
  if (stage === 'junior') return gradeIndex + 7
  return gradeIndex + 10
}

